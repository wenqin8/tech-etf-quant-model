"""帮助页: 面向量化新手的使用指南与名词解释。"""

from __future__ import annotations

import streamlit as st

st.title("帮助")
st.caption("第一次用? 从这里开始。")

st.subheader("这个工具是做什么的")
st.markdown(
    """
ETF Quant Lab 帮你用**规则化的策略**研究 A 股 ETF:

1. 每天收盘后自动**同步行情**并做**质量检查**;
2. 策略根据数据给出**目标持仓建议**(信号);
3. 你用**虚拟资金**跟随信号, 观察策略实际效果;
4. 用**回测**检验策略在过去几年的表现。

> ⚠️ 它**不连接券商、不会自动下单、不构成投资建议**。所有交易都是模拟的。
"""
)

st.subheader("日常使用流程")
st.markdown(
    """
| 时间 | 做什么 | 在哪做 |
|---|---|---|
| 每个交易日 16:30 后 | 点一次「运行每日流水线」 | 数据中心 |
| 之后 | 查看当日信号与入选原因 | 今日信号 |
| 想跟随时 | 确认模拟下单 | 模拟账户 |
| 随时 | 查看净值曲线判断策略效果 | 模拟账户 |
| 出问题时 | 看失败原因 | 运行日志 |

不想手动? 在终端运行 `uv run python scripts/run_scheduler.py`,
它会在每个交易日 16:30 自动完成流水线(窗口需保持开启)。
"""
)

st.subheader("名词速查")
st.markdown(
    """
| 名词 | 意思 |
|---|---|
| **信号** | 策略给出的目标持仓建议, 例如"创业板ETF 买到 30%" |
| **目标权重** | 某标的应占你总资产的比例 |
| **动量** | 近期涨势强度; 动量策略买入近期最强的标的 |
| **趋势均线** | 过去 N 天收盘价的平均; 价格在均线上方视为处于上升趋势 |
| **回测** | 用真实历史数据模拟策略过去的买卖, 检验其表现 |
| **年化收益** | 折算成"每年平均赚多少"的收益率 |
| **最大回撤** | 净值从最高点到最低点的最大跌幅, 衡量最坏情况有多坏 |
| **夏普比率** | 收益/波动的性价比; >1 优秀, <0 亏损 |
| **滑点** | 实际成交价比看到的价格差一点的成本假设 |
| **T+1** | A 股规则: 今天买的明天才能卖 |
| **质量门禁** | 自动数据体检; 有问题的数据会被拒绝, 不进入研究 |
| **幂等** | 同一操作重复执行不会产生重复记录(防手滑双击) |
"""
)

st.subheader("可以配置什么")
st.markdown(
    """
配置都在项目 `config/` 目录下的 YAML 文件里, 改完重启应用生效:

| 文件 | 管什么 | 常见修改 |
|---|---|---|
| `universe.yaml` | 研究哪些 ETF | 增删标的、启用/停用 |
| `strategy_presets.yaml` | 策略默认参数 | 调整持仓数量、均线窗口 |
| `cost_scenarios.yaml` | 回测成本假设 | 按你券商的实际佣金修改 |
| `app.yaml` | 运行参数 | 信号时间(signal_hour/minute) |

环境变量(可写入 `.env`): `EQL_TUSHARE_TOKEN`(备用数据源)、
`EQL_DATA_DIR`(数据目录) 等, 完整列表见 `.env.example`。
"""
)

st.subheader("常见问题")
with st.expander("为什么有一只 ETF 一直显示「已拒绝」?"):
    st.markdown(
        "免费数据源的价格没有处理基金份额拆分(例如银行ETF 512800 曾单日价格近乎减半), "
        "质量检查会把这种失真数据拦下来, 避免污染回测和信号。这是保护机制, 不是故障。"
    )
with st.expander("信号说买入, 我必须买吗?"):
    st.markdown(
        "不。信号只是策略规则的输出, 供研究参考。建议先用模拟账户跟踪一段时间, "
        "观察净值曲线后再自行判断。工具永远不会碰你的真实资金。"
    )
with st.expander("回测赚钱 = 以后也赚钱吗?"):
    st.markdown(
        "不是。历史表现不代表未来。本工具的回测已尽量保守(次日成交、计入成本), "
        "但仍只是历史证据。请结合「悲观」成本情景与最大回撤评估风险。"
    )
with st.expander("数据同步失败怎么办?"):
    st.markdown(
        "系统会自动: 先按代理再直连各重试一次 → 换备用数据源。仍失败时到「运行日志」"
        "看具体原因, 通常稍后重试即可。"
    )
